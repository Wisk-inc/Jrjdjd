// Build the three files that carry Scam Finder's code onto the site:
//
//   node tools/scam-radar/build-bundles.mjs        (needs npx; esbuild is fetched on first use)
//
//   assets/js/scam-finder-core.js        the offline name and link logic, for the browser
//   api/scam-finder.js                   the investigation API, for Vercel
//   netlify/functions/scam-finder.js     the same API, for Netlify
//
// Each is one self-contained file, so a host needs nothing from tools/ to run it. Run this after
// updating scam-finder/, sanitize.mjs or any of the entry files.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const here = import.meta.dirname;
const root = path.join(here, '..', '..');
const esbuild = (args) => execFileSync('npx', ['--yes', 'esbuild@0.28', ...args], { cwd: root, stdio: ['ignore', 'inherit', 'inherit'] });
const banner = (what) => `/* ${what} Generated by tools/scam-radar/build-bundles.mjs from Scam Finder (MIT, see tools/scam-radar/NOTICE.md). Do not edit. */`;

esbuild([
  'tools/scam-radar/browser-entry.mjs', '--bundle', '--format=iife', '--global-name=ScamFinderCore',
  '--platform=browser', '--target=es2020', '--minify', '--legal-comments=none',
  '--alias:node:crypto=./tools/scam-radar/shims/crypto.mjs', '--alias:node:net=./tools/scam-radar/shims/net.mjs',
  '--external:psl', `--banner:js=${banner("Scam Finder's offline name and link logic.")}`,
  '--outfile=assets/js/scam-finder-core.js',
]);

for (const [entry, out] of [['api-vercel.cjs', 'api/scam-finder.js'], ['api-netlify.cjs', 'netlify/functions/scam-finder.js']]) {
  esbuild([
    `tools/scam-radar/${entry}`, '--bundle', '--format=cjs', '--platform=node', '--target=node20',
    '--legal-comments=none', '--external:psl', '--external:node:sqlite',
    `--banner:js=${banner('Scam Finder as an API: GET /api/scam-finder?url=<link>.')}`,
    `--outfile=${out}`,
  ]);
}

for (const file of ['assets/js/scam-finder-core.js', 'api/scam-finder.js', 'netlify/functions/scam-finder.js']) {
  console.log(`${file}: ${Math.round(fs.statSync(path.join(root, file)).size / 1024)} KB`);
}
